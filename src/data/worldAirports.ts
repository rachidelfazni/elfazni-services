export function formatAirportLabel(airport: WorldAirport, language: string): string {
  if (language === 'tr') {
    return `${airport.cityTr} - ${airport.nameTr}, ${airport.countryTr} (${airport.code})`;
  }
  if (language === 'en') {
    return `${airport.cityEn} (${airport.nameEn}), ${airport.countryEn} (${airport.code})`;
  }
  if (language === 'fr') {
    return `${airport.cityFr} - ${airport.nameFr}, ${airport.countryFr} (${airport.code})`;
  }
  return `${airport.cityAr} (${airport.nameAr})، ${airport.countryAr} (${airport.code})`;
}

export function searchWorldAirports(query: string): WorldAirport[] {
  const q = query.trim().toLowerCase();
  if (!q) {
    return WORLD_AIRPORTS.slice(0, 12);
  }
  return WORLD_AIRPORTS.filter((a) => {
    const searchable = [
      a.code,
      a.cityAr,
      a.cityEn,
      a.cityTr,
      a.cityFr,
      a.nameAr,
      a.nameEn,
      a.nameTr,
      a.nameFr,
      a.countryAr,
      a.countryEn,
      a.countryTr,
      a.countryFr,
    ]
      .join(' ')
      .toLowerCase();
    return searchable.includes(q);
  }).slice(0, 14);
}
