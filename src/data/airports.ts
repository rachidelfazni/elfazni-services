export function formatAirportLabel(airport: AirportOption, lang: string): string {
  if (lang === 'tr') return `${airport.cityTr} - ${airport.nameTr} (${airport.code})`;
  if (lang === 'en') return `${airport.cityEn} - ${airport.nameEn} (${airport.code})`;
  if (lang === 'fr') return `${airport.cityFr} - ${airport.nameFr} (${airport.code})`;
  return `${airport.cityAr} - ${airport.nameAr} (${airport.code})`;
}

export function formatAirportCityAndCode(airport: AirportOption, lang: string): string {
  if (lang === 'tr') return `${airport.cityTr} (${airport.code})`;
  if (lang === 'en') return `${airport.cityEn} (${airport.code})`;
  if (lang === 'fr') return `${airport.cityFr} (${airport.code})`;
  return `${airport.cityAr} (${airport.code})`;
}

export function formatAirportCountry(airport: AirportOption, lang: string): string {
  if (lang === 'tr') return airport.countryTr;
  if (lang === 'en') return airport.countryEn;
  if (lang === 'fr') return airport.countryFr;
  return airport.countryAr;
}

export function filterAirports(query: string): AirportOption[] {
  const q = query.trim().toLowerCase();
  if (!q) return AIRPORTS;

  return AIRPORTS.filter((airport) => {
    return (
      airport.code.toLowerCase().includes(q) ||
      airport.cityAr.toLowerCase().includes(q) ||
      airport.cityTr.toLowerCase().includes(q) ||
      airport.cityEn.toLowerCase().includes(q) ||
      airport.cityFr.toLowerCase().includes(q) ||
      airport.nameAr.toLowerCase().includes(q) ||
      airport.nameTr.toLowerCase().includes(q) ||
      airport.nameEn.toLowerCase().includes(q) ||
      airport.nameFr.toLowerCase().includes(q) ||
      airport.countryAr.toLowerCase().includes(q) ||
      airport.countryTr.toLowerCase().includes(q) ||
      airport.countryEn.toLowerCase().includes(q) ||
      airport.countryFr.toLowerCase().includes(q)
    );
  });
}
